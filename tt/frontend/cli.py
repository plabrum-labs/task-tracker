# A refusal is the object's answer, not a usage error, so it is neither Click's 2
# nor a success. 123 is what the Rust and OCaml spikes both return for the same
# thing — distinct codes for the two refusals are a real tracker's problem and not
# this spike's.
REFUSED = 123

# The help of the two arguments the raw ``action`` path shares, factored out only
# so the command declarations stay one line each.
_KEY_HELP = "The action to run."
_JSON_HELP = "The action's arguments, as a JSON object."

# What a generated command hands its address and payload to.
type Writer = Callable[[Engine, Any, str, dict[str, Any]], str]

# How a generated command reads a row's current fields, keyed by field name, to
# fill in an edit the caller left partial.
type Reader = Callable[[Engine, Any], dict[str, Any]]

# The one action every object exposes as a whole-object write: it carries every
# editable field and sets each at once. Its generated subcommand takes the fields
# as optional flags and hydrates the ones omitted from the row's current state, so
# a caller changes one field without restating (or first reading) the rest.
_WHOLE_OBJECT_EDIT = "edit"


# --- rendering ------------------------------------------------------------


def _progress(counts: StatusCounts) -> str:
    """Done over the scope a progress bar measures. Canceled issues are off that
    scope — they were never going to finish — so ``total`` sums every other status:
    done of the work that was ever going to happen."""
    total = sum(count for status, count in counts.items() if status is not Status.CANCELED)
    return f"{counts[Status.DONE]}/{total}"


def _breakdown(counts: StatusCounts) -> str:
    """One "<n> <status>" per status, in workflow order. Canceled is off the
    workflow, so it joins only when something sits at it rather than trailing a
    "0 canceled" on every line."""
    return ", ".join(
        f"{counts[status]} {status.value}"
        for status in Status
        if status is not Status.CANCELED or counts[status]
    )


def _project_line(p: ProjectListItem) -> str:
    return f"{p.slug:<12} {p.title:<24} {p.status:<8} {_breakdown(p.counts)}"


def _issue_line(i: IssueListItem) -> str:
    # A fixed-width marker column so an issue waiting on a dependency flags in the text
    # list without shifting the titles of the ones that are not.
    waiting = "⊘" if i.waiting else " "
    return f"{i.ref:<10} {i.status:<8} {i.priority:<6} {waiting} {i.title}"


def _epic_line(e: EpicListItem) -> str:
    due = e.due_date.isoformat() if e.due_date is not None else "—"
    return f"{e.status:<8} {due:<12} {_progress(e.counts):<8} {e.title}"


def _milestone_line(m: MilestoneListItem) -> str:
    due = m.due_date.isoformat() if m.due_date is not None else "—"
    epic = m.epic if m.epic is not None else "—"
    return f"{due:<12} {_progress(m.counts):<8} epic {epic:<20} {m.title}"


def _tag_line(t: TagListItem) -> str:
    return f"{t.id:<4} {t.name}"


def _offer_availability(offer: Offer) -> dict[str, Any]:
    """One offered action as an agent reads it when choosing what to do next: its
    key and label, whether it is runnable against the live row, and why not when it
    is refused. An action's argument schema is static per action, not per row, so it
    lives in the verb's own ``--help`` rather than being repeated on every read."""
    fields: dict[str, Any] = {"key": offer.key, "label": offer.label}
    match offer.state:
        case Runnable():
            fields["state"] = "runnable"
        case Refused(reason):
            fields["state"] = "refused"
            fields["reason"] = reason
    return fields


def _pretty(value: Any) -> str:
    return json.dumps(value, indent=2)


# --- the writes -----------------------------------------------------------

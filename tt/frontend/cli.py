app = typer.Typer(
    help="A small task tracker: a command line and a terminal UI.",
    add_completion=False,
)


@app.callback(invoke_without_command=True)
def _main(
    ctx: typer.Context,
    database: Annotated[
        str | None,
        typer.Option("--db", help="The database to open. Defaults to the shared per-user file."),
    ] = None,
    # ``version`` is consumed by its eager callback, not this body.
    version: Annotated[
        bool,
        typer.Option(
            "--version",
            callback=_version_callback,
            is_eager=True,
            help="Show the version and the checkout tt runs from, then exit.",
        ),
    ] = False,
) -> None:
    """Bare ``tt`` is the terminal UI; a subcommand is the command line. So the
    callback runs even with no subcommand, and opens the TUI when none was
    invoked. Textual is imported only on that branch, so a CLI command does not
    pay to load it."""
    engine = schema.bootstrap(database)
    ctx.obj = engine
    if ctx.invoked_subcommand is None:
        from tt.frontend import tui

        tui.run(engine)



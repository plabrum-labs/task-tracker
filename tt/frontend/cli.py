# A refusal is the object's answer, not a usage error, so it is neither Click's 2
# nor a success. 123 is what the Rust and OCaml spikes both return for the same
# thing — distinct codes for the two refusals are a real tracker's problem and not
# this spike's.
REFUSED = 123

# The help of the two arguments the raw ``action`` path shares, factored out only
# so the command declarations stay one line each.
_KEY_HELP = "The action to run."
_JSON_HELP = "The action's arguments, as a JSON object."

# What a generated command hands its address and payload to.
type Writer = Callable[[Engine, Any, str, dict[str, Any]], str]


# --- rendering ------------------------------------------------------------


def _project_line(p: ProjectListItem) -> str:
    counts = (
        f"{p.backlog} backlog, {p.planning} planning, {p.todo} todo, {p.doing} doing, {p.done} done"
    )
    return f"{p.slug:<12} {p.title:<24} {p.status:<8} {counts}"


def _issue_line(i: IssueListItem) -> str:
    return f"{i.ref:<10} {i.status:<8} {i.priority:<6} {i.title}"


def _epic_line(e: EpicListItem) -> str:
    total = e.backlog + e.planning + e.todo + e.doing + e.done
    progress = f"{e.done}/{total}"
    due = e.due_date.isoformat() if e.due_date is not None else "—"
    return f"{e.ref:<10} {e.status:<8} {due:<12} {progress:<8} {e.title}"


def _milestone_line(m: MilestoneListItem) -> str:
    total = m.backlog + m.planning + m.todo + m.doing + m.done
    progress = f"{m.done}/{total}"
    due = m.due_date.isoformat() if m.due_date is not None else "—"
    return f"{m.ref:<10} epic {m.epic:<10} {due:<12} {progress:<8} {m.title}"


def _tag_line(t: TagListItem) -> str:
    return f"{t.id:<4} {t.name}"


def _field_json(field: Field) -> dict[str, Any]:
    """One argument, as the JSON an agent reads before it fills anything in."""
    base: dict[str, Any] = {
        "name": field.name,
        "required": field.required,
        "description": field.description,
    }
    match field.kind:
        case actions.Text():
            return {**base, "type": "text"}
        case actions.OptionalText():
            return {**base, "type": "text", "optional": True}
        case actions.Date():
            return {**base, "type": "date"}
        case actions.Reference():
            return {**base, "type": "ref"}
        case Enum(values=values):
            return {**base, "type": "enum", "values": values}


def _offer_json(offer: Offer) -> dict[str, Any]:
    """One offered action, as the JSON an agent reads before it picks anything."""
    fields: dict[str, Any] = {"key": offer.key, "label": offer.label}
    match offer.state:
        case Runnable():
            fields["state"] = "runnable"
        case Refused(reason):
            fields["state"] = "refused"
            fields["reason"] = reason
    fields["arguments"] = [_field_json(field) for field in offer.fields]
    return fields


def _pretty(value: Any) -> str:
    return json.dumps(value, indent=2)


# --- the writes -----------------------------------------------------------
#
# The ``api`` opens the transaction, so one call is one write with no ``with``
# here: the hooks are checked against the row as it is now rather than as some
# earlier detail view reported it, and a refusal after rows are written rolls the
# whole call back. A project write carries an optional slug — an object action
# passes one, the top-level ``createProject`` passes ``None``.


def _project_write(engine: Engine, slug: Any, key: str, payload: dict[str, Any]) -> str:
    return project_api.project_action(engine, key, payload, slug).message


def _issue_write(engine: Engine, ref: Any, key: str, payload: dict[str, Any]) -> str:
    return issue_api.issue_action(engine, key, payload, ref).message


def _epic_write(engine: Engine, ref: Any, key: str, payload: dict[str, Any]) -> str:
    return epic_api.epic_action(engine, key, payload, ref).message


def _milestone_write(engine: Engine, ref: Any, key: str, payload: dict[str, Any]) -> str:
    return milestone_api.milestone_action(engine, key, payload, ref).message


def _tag_write(engine: Engine, tag_id: Any, key: str, payload: dict[str, Any]) -> str:
    return tag_api.tag_action(engine, key, payload, tag_id).message


def _comment_write(engine: Engine, comment_id: Any, key: str, payload: dict[str, Any]) -> str:
    return comment_api.comment_action(engine, key, payload, comment_id).message


def _project_init(
    engine: Engine, slug: str, title: str | None, body: str | None, path: str | None
) -> str:
    """``createProject`` with the directory it binds filled in.

    ``init`` names the ``createProject`` key rather than being generated like the
    object actions: a top-level create has no address to hang a subcommand on, and
    ``init``'s point is a default no generated command could supply. The project
    binds to the current directory unless ``--path`` overrides it, so bare ``tt``
    resolves and opens it there afterwards.
    """
    directory = os.path.abspath(os.path.expanduser(path)) if path is not None else os.getcwd()
    payload: dict[str, Any] = {"slug": slug, "path": directory}
    if title is not None:
        payload["title"] = title
    if body is not None:
        payload["body"] = body
    return _project_write(engine, None, "createProject", payload)


# --- the reads ------------------------------------------------------------


def _project_ls(engine: Engine, as_json: bool) -> str:
    items = project_api.project_list(engine)
    if as_json:
        return _pretty([item.model_dump(mode="json") for item in items])
    return "\n".join(_project_line(p) for p in items)


def _parse_sort(raw: str | None) -> IssueSort:
    """A ``--sort`` value, ``<field>[:<direction>]``, as the sort it names. A bad
    field or direction is a usage error listing what is allowed, not a refusal — it
    is the invocation that is wrong, not the data."""
    if raw is None:
        return IssueSort()
    field_text, sep, direction_text = raw.partition(":")
    try:
        field = SortField(field_text)
    except ValueError as e:
        allowed = ", ".join(f.value for f in SortField)
        raise typer.BadParameter(
            f"unknown sort field {field_text!r}; choose one of {allowed}"
        ) from e
    if not sep:
        return IssueSort(field=field)
    try:
        direction = Direction(direction_text)
    except ValueError as e:
        raise typer.BadParameter(
            f"unknown sort direction {direction_text!r}; use asc or desc"
        ) from e
    return IssueSort(field=field, direction=direction)


def _epic_id(engine: Engine, project_slug: str, ref: str) -> int:
    """The id of the epic a ref names within the project, or a refusal. The ref
    carries its own project's slug, so one from another project is no epic here."""
    epic = epic_api.epic_get(engine, ref)
    if epic is None or epic.project != project_slug:
        raise Invalid(f"no epic {ref} in project {project_slug!r}")
    return epic.id


def _milestone_id(engine: Engine, project_slug: str, ref: str) -> int:
    """The id of the milestone a ref names within the project, or a refusal. A
    milestone's ref is ``<project slug>-<number>`` like an epic's, so its slug is
    what places it in the project."""
    milestone = milestone_api.milestone_get(engine, ref)
    parsed = parse_ref(ref)
    if milestone is None or parsed is None or parsed[0] != project_slug:
        raise Invalid(f"no milestone {ref} in project {project_slug!r}")
    return milestone.id


def _issue_ls(
    engine: Engine,
    project_slug: str | None,
    tag: str | None,
    epic: str | None,
    milestone: str | None,
    sort: IssueSort,
    as_json: bool,
) -> str:
    if project_slug is None:
        # An epic or milestone ref is project-scoped, so filtering by one only makes
        # sense once a project is named; a bare ref would range over every project.
        if epic is not None or milestone is not None:
            raise typer.BadParameter("--epic and --milestone need --project")
        slugs = [p.slug for p in project_api.project_list(engine)]
        filter = IssueFilter(tag=tag)
    else:
        if project_api.project_get(engine, project_slug) is None:
            raise Invalid(f"no project {project_slug!r}")
        slugs = [project_slug]
        filter = IssueFilter(
            tag=tag,
            epic_id=_epic_id(engine, project_slug, epic) if epic is not None else None,
            milestone_id=_milestone_id(engine, project_slug, milestone)
            if milestone is not None
            else None,
        )
    items = [issue for slug in slugs for issue in issue_api.issue_list(engine, slug, filter, sort)]
    if as_json:
        return _pretty([item.model_dump(mode="json") for item in items])
    return "\n".join(_issue_line(i) for i in items)


def _epic_ls(engine: Engine, project_slug: str | None, as_json: bool) -> str:
    if project_slug is not None:
        if project_api.project_get(engine, project_slug) is None:
            raise Invalid(f"no project {project_slug!r}")
        slugs = [project_slug]
    else:
        slugs = [p.slug for p in project_api.project_list(engine)]
    items = [epic for slug in slugs for epic in epic_api.epic_list(engine, slug)]
    if as_json:
        return _pretty([item.model_dump(mode="json") for item in items])
    return "\n".join(_epic_line(e) for e in items)


def _project_show(engine: Engine, slug: str) -> str:
    detail, offers = project_api.project_detail(engine, slug)
    actions = [_offer_json(offer) for offer in offers]
    return _pretty({"project": detail.model_dump(mode="json"), "actions": actions})


def _epic_show(engine: Engine, ref: str) -> str:
    detail, offers = epic_api.epic_detail(engine, ref)
    actions = [_offer_json(offer) for offer in offers]
    return _pretty({"epic": detail.model_dump(mode="json"), "actions": actions})


def _epic_ids(engine: Engine) -> list[int]:
    """Every live epic id across every live project — what a milestone list with no
    epic named ranges over. Ids, not refs: they feed ``milestone_list``, which reads
    by the epic's own id rather than resolving a ref per epic."""
    return [
        epic.id
        for project in project_api.project_list(engine)
        for epic in epic_api.epic_list(engine, project.slug)
    ]


def _milestone_ls(engine: Engine, epic_ref: str | None, as_json: bool) -> str:
    if epic_ref is not None:
        epic = epic_api.epic_get(engine, epic_ref)
        if epic is None:
            raise Invalid(f"no epic {epic_ref}")
        epic_ids = [epic.id]
    else:
        epic_ids = _epic_ids(engine)
    items = [m for eid in epic_ids for m in milestone_api.milestone_list(engine, eid)]
    if as_json:
        return _pretty([item.model_dump(mode="json") for item in items])
    return "\n".join(_milestone_line(m) for m in items)


